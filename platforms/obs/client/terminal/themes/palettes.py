#!/usr/bin/env python3
"""Colour variants of polarlicht for comparison: writes pl-<name>.css next to every
polarlicht.css (screens, overlay terminal pages, bars - see TARGETS), each a copy of it with its
colours mapped onto another palette. Shown side by side by
features/overlay/client/vorschau.html.

polarlicht is built from a few colour families, and each is mapped as a family rather than
colour by colour, so gradients, glows and the rising gear keep their light/dark relations:

    cyan    (hue 160-210)   -> the palette's main colour A
    magenta (hue 300-350)   -> its second colour B
    violet  (hue 260-300)   -> the middle between A and B (the gradients' midpoints)
    navy    (dark, 220-260) -> the palette's background hue
    whites, greys, black    stay

Run again after changing polarlicht.css or a palette:  python3 palettes.py
"""
import colorsys
import re
from pathlib import Path

HERE = Path(__file__).parent

# name: (label, main colour A, second colour B, background hue in degrees)
PALETTES = {
    "polarlicht":  ("Polarlicht (aktuell)", "#5FEAF5", "#F22A80", 235),
    "wafobi":      ("Wafobi-Logo",          "#26D5D5", "#A72ED9", 238),
    "sunset":      ("Sonnenuntergang",      "#FFB347", "#FF3F86", 275),
    "synthwave":   ("Synthwave",            "#FF4FD8", "#7B5CFF", 255),
    "toxic":       ("Toxic",                "#9BFF5C", "#1FC8FF", 215),
    "ozean":       ("Ozean",                "#4FC3FF", "#2FFFB4", 210),
    "lava":        ("Lava",                 "#FFD34F", "#FF3B2F", 350),
    "eis":         ("Eis",                  "#DDF3FF", "#5B86FF", 228),
    "vapor":       ("Vaporwave",            "#B48CFF", "#45F0D0", 260),
}

REF_A, REF_B = "#5FEAF5", "#F22A80"


def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#" + "".join(f"{round(max(0, min(1, c)) * 255):02X}" for c in rgb)


def hls(rgb):
    return colorsys.rgb_to_hls(*rgb)


def shift(rgb, ref, target):
    """Move a colour from its family's reference to the target, keeping its offset."""
    h, l, s = hls(rgb)
    rh, rl, rs = hls(ref)
    th, tl, ts = hls(target)
    l2 = max(0, min(1, l + (tl - rl) * (0.6 + 0.4 * (1 - abs(l - rl)))))
    s2 = max(0, min(1, s * (ts / rs if rs else 1)))
    return colorsys.hls_to_rgb(th, l2, s2)


def mapper(a, b, bg_hue):
    A, B, RA, RB = hex_to_rgb(a), hex_to_rgb(b), hex_to_rgb(REF_A), hex_to_rgb(REF_B)
    mid = tuple((x + y) / 2 for x, y in zip(A, B))
    ref_mid = tuple((x + y) / 2 for x, y in zip(RA, RB))

    def convert(rgb):
        h, l, s = hls(rgb)
        deg = h * 360
        if s < 0.12 or l > 0.93 or l < 0.03:
            return rgb                                   # white, grey, black
        if l < 0.32 and 215 <= deg <= 290:
            return colorsys.hls_to_rgb(bg_hue / 360, l, s)   # the navy grounds
        if 160 <= deg <= 210:
            return shift(rgb, RA, A)
        if 300 <= deg <= 352:
            return shift(rgb, RB, B)
        if 255 <= deg < 300:
            return shift(rgb, ref_mid, mid)
        return rgb
    return convert


HEX = re.compile(r"(#|%23)([0-9A-Fa-f]{6})\b")
RGBA = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)")


def recolour(css, convert):
    def hex_sub(m):
        out = rgb_to_hex(convert(hex_to_rgb(m.group(2))))
        return m.group(1) + out[1:]

    def rgba_sub(m):
        rgb = convert(tuple(int(m.group(i)) / 255 for i in (1, 2, 3)))
        r, g, b = (round(max(0, min(1, c)) * 255) for c in rgb)
        return f"rgba({r}, {g}, {b}{m.group(4) or ', 1'})"
    return RGBA.sub(rgba_sub, HEX.sub(hex_sub, css))


# every polarlicht.css there is: the screens' copy here, the overlay's copy (chat, avatar frame,
# background) and the bars' own polarlicht - so a palette colours whole scenes
ROOT = HERE.parents[4]
TARGETS = [HERE, ROOT / "features/overlay/client/terminal/themes", ROOT / "features/overlay/client/themes"]


def main():
    for folder in TARGETS:
        source = (folder / "polarlicht.css").read_text()
        for name, (label, a, b, bg) in PALETTES.items():
            if name == "polarlicht":
                continue
            head = (f"/* GENERATED by platforms/obs/client/terminal/themes/palettes.py from polarlicht.css -\n"
                    f"   palette \"{label}\" ({a} / {b}). Do not edit; change polarlicht.css or palettes.py\n"
                    f"   and run it again. */\n")
            (folder / f"pl-{name}.css").write_text(head + recolour(source, mapper(a, b, bg)))
        print(f"{folder.relative_to(ROOT)}: {len(PALETTES) - 1} palettes")


if __name__ == "__main__":
    main()
